-- Настройки цеха у каждой компании свои.
--
-- Толщины и зазоры участвуют в расчёте детализировки: захардкоженные
-- значения сделали бы её неверной для половины клиентов, а неверная
-- детализировка хуже её отсутствия — по ней распилят плиту.
alter table public.orgs
  add column if not exists production jsonb not null default '{}'::jsonb;

comment on column public.orgs.production is
  'Настройки производства: толщины ЛДСП/фасада/ХДФ, тип задней стенки, зазор фасада, видимая кромка.';
