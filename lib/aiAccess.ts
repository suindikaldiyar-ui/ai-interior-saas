import { NextResponse } from 'next/server';
import { isDemoPlan } from './plan';
import { currentOrg } from './supabase/server';

/**
 * ГЕНЕРАЦИЯ ВЫКЛЮЧЕНА У ДЕМО-ОРГАНИЗАЦИЙ — НА СЕРВЕРЕ.
 *
 * Спрятать кнопку мало: демо-страницу открывает кто угодно сколько угодно
 * раз, а запрос к модели стоит денег за каждую картинку. Кнопки в интерфейсе
 * нет, но отказывает именно роут — иначе защита держится на вёрстке.
 *
 * ОТКАЗ ТОЧЕЧНЫЙ, И ЭТО ГЛАВНОЕ СВОЙСТВО ЭТОЙ ФУНКЦИИ:
 *
 *   организация с plan='demo'  → 403 с внятным текстом
 *   любой другой тариф          → пропускаем
 *   организации нет вовсе       → пропускаем
 *
 * Последняя строка не оплошность, а условие «мой путь не задет»: роуты
 * генерации сессии никогда не требовали (их зовёт и `/demo`, и студия),
 * и требовать её сейчас значило бы сломать работающее ради чужого тарифа.
 * Демо-компания сюда не попадёт: её люди ходят по своим объектам под своей
 * сессией, а публичная страница не генерирует вовсе.
 */
export async function generationBlocked(what: string): Promise<NextResponse | null> {
  const org = await currentOrg();
  if (!org || !isDemoPlan(org.plan)) return null;

  return NextResponse.json(
    {
      error:
        `Визуализация в демонстрационном доступе выключена: ${what} здесь не запускается. ` +
        'Готовая визуализация уже лежит на вашей демо-странице, а живая отрисовка ' +
        'включается вместе с рабочим доступом.',
      code: 'demo_plan',
    },
    { status: 403 },
  );
}
