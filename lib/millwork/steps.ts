/**
 * Четыре шага рабочего экрана.
 *
 * На всех четырёх слева стоит одна и та же сцена: замерщик не должен
 * терять мебель из виду, переходя между шагами, — он показывает её
 * клиенту, и пропавшая с экрана мебель обрывает разговор.
 */
export const STUDIO_STEPS: StepKey[] = ['sizes', 'layout', 'build', 'materials'];

export function isStudio(step: StepKey): boolean {
  return STUDIO_STEPS.includes(step);
}

/** Показывать ли этот блок на этом шаге. */
export function shows(step: StepKey, field: StepField): boolean {
  return STEP_FIELDS[step].includes(field);
}

/**
 * Порядок шагов.
 *
 * Замер появляется, только если он есть: у объекта из библиотеки
 * планировок его может не быть вовсе, и пустой шаг в полосе обещал бы
 * работу, которой нет.
 */
export function stepOrder(hasSurvey: boolean): StepKey[] {
  return [
    ...(hasSurvey ? (['survey'] as StepKey[]) : []),
    'template',
    'sizes',
    'layout',
    'build',
    'materials',
    'result',
  ];
}

/**
 * ПЕРЕХОД — ЭТО ТОЛЬКО ШАГ.
 *
 * Ни выделенный модуль, ни активная стена, ни автосохранение переходом
 * не трогаются (ловушка 60): состояние живёт в одном месте, а шаг — это
 * лишь то, что показано. Поэтому здесь чистые функции, возвращающие
 * ключ, и ничего кроме.
 */
export function nextStep(order: StepKey[], step: StepKey): StepKey {
  const at = order.indexOf(step);
  if (at < 0) return order[0];
  return order[Math.min(order.length - 1, at + 1)];
}

export function prevStep(order: StepKey[], step: StepKey): StepKey {
  const at = order.indexOf(step);
  if (at < 0) return order[0];
  return order[Math.max(0, at - 1)];
}
