/**
 * ШАГИ РАБОТЫ — ОДИН СПИСОК НА ПРОДУКТ.
 *
 * Конфигуратор держал всё сразу: техника, материал, варианты, состав —
 * одним списком в правой панели. Панель от этого росла до четырёх
 * экранов прокрутки, и замерщик искал в ней поле вместо того, чтобы
 * вести разговор.
 *
 * Теперь работа разложена на четыре шага, и у каждого свой предмет:
 *
 *   РАЗМЕРЫ     — стены, потолок, отметки цеха: рамка, внутри которой
 *                 всё остальное вообще возможно;
 *   РАСКЛАДКА   — что стоит в ряду: модули, ширина, техника, порядок;
 *   КОНСТРУКЦИЯ — что внутри модуля: полки, ящики, открывание, ручка;
 *   МАТЕРИАЛЫ   — из чего это сделано: фасад, столешница, цвет, артикул.
 *
 * Разложение живёт ЗДЕСЬ, а не в разметке: экран читает этот список и
 * рисует то, что в нём написано. Вторая таблица «что на каком шаге»
 * разошлась бы с первой на первой же новой кнопке, и поле пропало бы с
 * экрана молча — а найти пропажу из интерфейса нельзя.
 */

export type StepKey =
  | 'survey'
  | 'template'
  | 'sizes'
  | 'layout'
  | 'build'
  | 'materials'
  | 'result';

/**
 * Блоки панели.
 *
 * Ключ — это не название кнопки, а предмет разговора: под ним может
 * лежать и одна кнопка, и целый компонент. Экран спрашивает по ключу,
 * тест — по нему же.
 */
export type StepField =
  /* ── Размеры ── */
  /** Форма гарнитура, переключатель стен, решение угла. */
  | 'walls'
  /** Отметки цеха: рабочая поверхность, фартук, цоколь, глубины. */
  | 'shop'
  /* ── Раскладка ── */
  /** Лента модулей, ширина, техника, тип, добавить и убрать. */
  | 'modules'
  /** Перенос прибора на другую стену. */
  | 'appliance-wall'
  /** Две-три компоновки одной кухни. */
  | 'arrangements'
  /** Командная строка: правка состава словами. */
  | 'command'
  /* ── Конструкция ── */
  /** Что бывает в этом месте: карго, витрина, сушилка. */
  | 'variants'
  /** Наполнение модуля: число фронтов и секция. */
  | 'filling'
  /** Направление открывания и ручка. */
  | 'opening'
  /* ── Материалы ── */
  /** Материал фасада выбранного модуля: образцы и атрибуты. */
  | 'front'
  /** Готовые дизайны: материал на весь ряд одним тапом. */
  | 'designs'
  /** Артикулы каталога: фасады, столешница, фартук. */
  | 'catalog'
  /** Фото помещения — вход визуализации. */
  | 'photo';

