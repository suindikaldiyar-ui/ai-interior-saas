import type { MillingLayer } from './milling';

/**
 * РЕЛЬЕФ ФРЕЗЕРОВКИ: ОДНА МОДЕЛЬ ГЛУБИНЫ И СВЕТА.
 *
 * Профиль показывают в двух местах — карточкой выбора и фасадом в сцене, —
 * и до этого они считали тень по-разному: карточка обводила контур со
 * смещением, сцена пекла карту нормалей. Две модели одного и того же дают
 * одну картинку на карточке и другую на мебели, а клиент выбирает по
 * первой и получает вторую.
 *
 * Здесь лежат ЧИСЛА, общие для обоих: куда падает свет, насколько крута
 * стенка выборки и насколько темнеет дно с глубиной. Рисуют их по-разному
 * — вектором на карточке и пикселями в текстуре, — но считают одинаково.
 *
 * Модуль намеренно чистый: ни three, ни DOM. Карточка живёт в бандле
 * конфигуратора, который обязан открываться быстро на планшете
 * (ловушка 27), а `milledNormal.ts` тянет three.
 */

/** Поле профиля: контуры каталога нарисованы в квадрате 100×100. */
export const PROFILE_SPAN = 100;

/**
 * ПРОФИЛЬ — ЭТО ДОЛЯ ФАСАДА, А НЕ МИЛЛИМЕТРЫ.
 *
 * Контур ложится на фасад ЦЕЛИКОМ: в сцене текстура натянута на полотно
 * один раз (`repeat 1×1`, без повтора), на карточке поле профиля равно
 * полотну. Значит координата пути — это процент габарита: рамка в четыре
 * единицы на дверце 400 мм даёт 16 мм, а на дверце 900 мм — 36 мм.
 *
 * Фиксированные миллиметры здесь были бы враньём: филёнка узкой дверцы
 * и филёнка широкой — разные по размеру, это видно глазом и так их и
 * фрезеруют.
 */
export function profileMm(units: number, facadeMm: number): number {
  return (units / PROFILE_SPAN) * facadeMm;
}

/**
 * СВЕТ ОДИН И СВЕРХУ СЛЕВА.
 *
 * Тангенциальное пространство: X вправо, Y вверх, Z на зрителя. Второй
 * источник или другой угол на карточке сделал бы утопленное выпуклым —
 * ровно та ошибка, из-за которой рельеф читается наизнанку.
 */
export const RELIEF_LIGHT = { x: -0.5, y: 0.5, z: 0.71 };

/**
 * НАСКОЛЬКО КРУТА СТЕНКА ВЫБОРКИ.
 *
 * Было 2.6 — и на общем виде сцены рельеф пропадал: фасад читался
 * гладким, а платят за фрезерованный. Поднято до 4.2: профиль виден с
 * общего вида и не превращается в штамповку вблизи (проверено снимками
 * общего вида и вида спереди).
 */
export const RELIEF_SLOPE = 4.2;

/**
 * СИЛА КАРТЫ НОРМАЛЕЙ НА МАТЕРИАЛЕ.
 *
 * Было 1.0 (умолчание three) — профиль пропадал на общем виде. 1.6 даёт
 * читаемый рельеф с общего вида и не делает фасад штампованным вблизи.
 */
export const RELIEF_NORMAL_SCALE = 1.6;

/** Дно самой глубокой выборки темнее плоскости фасада во столько раз. */
const FLOOR_DARKEN = 0.22;

export type LayerShade = {
  /** Затемнение дна выборки: 0 — плоскость фасада. */
  floor: number;
  /** Тень по кромке, отвернувшейся от света. */
  shadow: number;
  /** Блик по кромке, обращённой к свету. */
  highlight: number;
  /** Смещение кромки в долях поля профиля: чем глубже, тем шире стенка. */
  edge: number;
};

/**
 * Тон одного слоя по его глубине.
 *
 * Стенка выборки наклонена: её нормаль отклоняется от плоскости фасада
 * тем сильнее, чем круче стенка (`RELIEF_SLOPE`) и чем глубже слой.
 * Освещённость считается ламбертом от `RELIEF_LIGHT` — тем же светом, по
 * которому печётся карта нормалей.
 */
export function layerShade(depth: number): LayerShade {
  const d = Math.min(1, Math.max(0, depth));

  /* Наклон стенки в тангенциальном пространстве: тот же, что у карты. */
  const tilt = Math.min(0.92, d * RELIEF_SLOPE * 0.22);
  const flat = Math.sqrt(Math.max(0, 1 - tilt * tilt));

  /* Стенка, отвёрнутая от света, и стенка, обращённая к нему. */
  const away = RELIEF_LIGHT.z * flat - (RELIEF_LIGHT.x + RELIEF_LIGHT.y) * tilt * 0.5;
  const toward = RELIEF_LIGHT.z * flat + (RELIEF_LIGHT.x + RELIEF_LIGHT.y) * tilt * 0.5;

  return {
    floor: d * FLOOR_DARKEN,
    shadow: Math.min(0.62, Math.max(0, RELIEF_LIGHT.z - away) + d * 0.3),
    highlight: Math.min(0.58, Math.max(0, toward - RELIEF_LIGHT.z) + d * 0.28),
    edge: 1.4 + d * 2.6,
  };
}

/**
 * Высота слоя в поле высот карты нормалей: 1 — плоскость фасада, 0 — дно.
 *
 * То же число, что даёт `layerShade.floor`, только с другой стороны: там
 * «насколько темнее», здесь «насколько ниже». Одна шкала на обе стороны.
 */
export function layerHeight(layer: MillingLayer): number {
  const d = Math.min(1, Math.max(0, layer.depth));
  return 1 - d * 0.85;
}
