/**
 * ПОДАЧА ЧЕРТЁЖНОГО ЛИСТА.
 *
 * Лист — это ДОКУМЕНТ, а не экран приложения. Мебельщик сверяет его с тем,
 * что выдаёт Базис: белая бумага, чёрная линейная графика, заливки по типу
 * элемента, штриховка сечения. Лист в цветах тёмной темы он всерьёз не
 * воспринимает, каким бы верным ни был расчёт под ним.
 *
 * Здесь только ПОДАЧА: ни одного числа геометрии, ни одной величины из
 * `fill` или сметы. Виды берут отсюда толщины и заливки — и ничего больше.
 */

/* ─────────────────────────  Толщины линий  ───────────────────────── */

/**
 * ТОЛЩИНЫ ЗАДАЮТСЯ В МИЛЛИМЕТРАХ БУМАГИ, а не в единицах SVG.
 *
 * Это то же правило, что у размеров: при 1:25 и при 1:50 контур обязан
 * выглядеть одинаково толстым НА БУМАГЕ. Задай толщину в единицах вида —
 * и на мелком масштабе линии слипнутся в кашу, а на крупном разъедутся
 * в жирные полосы.
 *
 * Ряд отраслевой: основная видимая линия вдвое толще внутренней, размерная
 * ещё тоньше. Глаз читает иерархию, не задумываясь.
 */
export const LINE_MM = {
  /** Видимый контур корпуса — основная линия. */
  contour: 0.5,
  /** Внутренние линии: полки, перегородки, швы фасадов. */
  inner: 0.25,
  /** Размерные, выносные и линии-выноски. */
  dimension: 0.18,
  /** Осевые: штрихпунктир. */
  axis: 0.18,
  /** Невидимый контур: штриховая. */
  hidden: 0.25,
} as const;

export type LineRole = keyof typeof LINE_MM;

/**
 * Сколько единиц вида приходится на миллиметр бумаги.
 *
 * Единственный мост между внутренней системой координат вида и бумагой.
 * Вид шириной `viewBoxUnits` печатается полосой `paperWidthMm` — значит
 * миллиметр бумаги это `viewBoxUnits / paperWidthMm` единиц.
 */
export function unitsPerPaperMm(viewBoxUnits: number, paperWidthMm: number): number {
  if (!(viewBoxUnits > 0) || !(paperWidthMm > 0)) return 1;
  return viewBoxUnits / paperWidthMm;
}

/** Толщины линий этого вида, в его собственных единицах. */
export function lineWidths(u: number): Record<LineRole, number> {
  return {
    contour: LINE_MM.contour * u,
    inner: LINE_MM.inner * u,
    dimension: LINE_MM.dimension * u,
    axis: LINE_MM.axis * u,
    hidden: LINE_MM.hidden * u,
  };
}

/** Штрих осевой линии: 8 мм штрих, 2 мм пробел, 1 мм точка. */
export function axisDash(u: number): string {
  return `${8 * u} ${2 * u} ${1 * u} ${2 * u}`;
}

/** Штрих невидимого контура: 3 мм через 2 мм. */
export function hiddenDash(u: number): string {
  return `${3 * u} ${2 * u}`;
}

/* ─────────────────────────  Заливки  ───────────────────────── */

/**
 * ЗАЛИВКИ РАЗЛИЧАЮТСЯ В ЧЁРНО-БЕЛОЙ ПЕЧАТИ.
 *
 * Лист печатают в цеху на обычном принтере. Цвет там пропадает, поэтому
 * элементы различаются СВЕТЛОТОЙ и ШТРИХОВКОЙ, а не оттенком — то же
 * правило, что у материалов на аксонометрии.
 *
 * Проволочный каркас, который был здесь раньше, глаз не разбирает вовсе:
 * корпус, фасад и техника выглядели одинаково, и чертёж читался как схема.
 */
export const PAPER_FILL = {
  /** Корпус ЛДСП: светло-серая заливка. */
  carcass: '#e8e8e8',
  /** Глухой фасад: белый с контуром — он и есть основная плоскость вида. */
  front: '#ffffff',
  /** Стекло: белое поле под редкой диагональной штриховкой. */
  glass: '#ffffff',
  /** Открытая ниша: заливки нет вовсе, видно нутро. */
  open: 'none',
  /** Техника: серая заливка, темнее корпуса. */
  appliance: '#c9c9c9',
  /** Столешница в разрезе: тёмная узкая полоса. */
  countertop: '#4a4a4a',
  /** Бумага под всем этим. */
  paper: '#ffffff',
} as const;

export type FillRole = keyof typeof PAPER_FILL;

/* ─────────────────────────  Штриховки  ───────────────────────── */

/**
 * ШТРИХОВКА СЕЧЕНИЯ — ЭТО ТО, ЧТО ОТЛИЧАЕТ РАЗРЕЗ ОТ ВИДА.
 *
 * Без неё разрез и фасад выглядят одинаково, и читающий не понимает, что
 * перед ним разрезанный материал. Плотная под 45° — сечение, редкая
 * под 45° в другую сторону — стекло.
 *
 * Шаг задан в МИЛЛИМЕТРАХ БУМАГИ по той же причине, что и толщины: иначе
 * на 1:50 штриховка схлопнется в заливку.
 */
export const HATCH_MM = {
  /** Разрезанный материал: плотно, 1.2 мм. */
  section: 1.2,
  /** Стекло: редко, 2.6 мм. */
  glass: 2.6,
} as const;

export type HatchRole = keyof typeof HATCH_MM;

/**
 * Идентификатор паттерна.
 *
 * Идентификаторы в SVG глобальны на документ, а на листе несколько видов
 * с РАЗНЫМ числом единиц в миллиметре: один общий паттерн дал бы на
 * половине видов неверный шаг. Поэтому у каждого вида свой.
 */
export function hatchId(view: string, role: HatchRole): string {
  return `mw-hatch-${role}-${view}`;
}
