/**
 * Ключ строки `renders` для рендера по чертежу.
 *
 * Таблица одна на все картинки объекта (ловушка 19 — второй таблицы под
 * вид картинки нет); отличает эту строку `style_id`. В сравнение «до и
 * после» она не идёт: там справа фото помещения с кухней, а здесь кухня в
 * комнате по замеру, снятая из сцены, — ракурсы у них разные.
 */
export const PATHTRACE_STYLE_ID = 'pathtrace';

/** Имя файла в Storage начинается так — по нему находится прежний. */
export const PATHTRACE_FILE_PREFIX = 'pathtrace-';

/**
 * Сколько проходов считать: выбор человека.
 *
 * Проход — одна выборка света на каждый пиксель. Шум уходит как корень
 * из числа проходов: 16 — черновик, чтобы проверить ракурс; 256 — картинка
 * для клиента; 1024 — для печати. Умолчание одно на все устройства: на
 * планшете меньше РАЗМЕР, а не качество.
 */
export const PATHTRACE_PASSES = [16, 64, 256, 1024] as const;
export const PATHTRACE_DEFAULT_PASSES = 256;

export type PathTraceSize = { key: string; width: number; height: number; title: string };

/**
 * Размер картинки: 1920×1080 на компьютере, 1280×720 на планшете.
 *
 * На планшете меньше пикселей — это в 2.25 раза меньше работы видеокарте
 * и памяти под накопление; разница видна на печати, а не на экране
 * планшета. Выбрать полный размер можно и там — это сказано словами.
 */
export const PATHTRACE_SIZES: PathTraceSize[] = [
  { key: '1920x1080', width: 1920, height: 1080, title: '1920 × 1080' },
  { key: '1280x720', width: 1280, height: 720, title: '1280 × 720 · планшет' },
];

export function pathTraceSize(key: string): PathTraceSize {
  return PATHTRACE_SIZES.find((size) => size.key === key) ?? PATHTRACE_SIZES[0];
}

/** Картинка рендера на экране: в памяти вкладки или уже в Storage. */
export type PathImage = {
  url: string;
  width: number;
  height: number;
  /** Проходов досчитано; у сохранённой раньше — неизвестно. */
  samples: number | null;
  /** Время счёта, мс; у сохранённой раньше — из строки `renders`. */
  ms: number | null;
  /** Лежит ли она в Storage вместе с объектом. */
  saved: boolean;
};
