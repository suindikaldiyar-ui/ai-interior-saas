import type { Module, Run, ZoneKind } from '@/types/millwork';

/**
 * НУМЕРАЦИЯ ПОЗИЦИЙ.
 *
 * У каждого изделия на объекте свой номер: **МИ-поз.1**, **МИ-поз.2** —
 * мебель индивидуальная, позиция N. Номер стоит в заголовке вида и в
 * спецификации, и по нему на монтаже говорят: «поз.3 идёт в спальню».
 *
 * Номера СКВОЗНЫЕ ПО ОБЪЕКТУ, а не по зоне: две кухни в одной квартире
 * бывают (основная и в гостевой), а два «поз.1» на объекте — это спор
 * бригады с бригадой при разгрузке.
 */

/**
 * Как изделие называется в штампе.
 *
 * «Кухня» — это помещение, а в штампе стоит ИЗДЕЛИЕ: кухонный гарнитур.
 * По этой строке на производстве понимают, что приехало.
 */
export const PRODUCT_TITLE: Record<ZoneKind, string> = {
  kitchen: 'Кухонный гарнитур',
  bedroom: 'Шкаф-купе',
  hallway: 'Прихожая',
  living: 'Мебель зала',
  bathroom: 'Мебель санузла',
};

/** Префикс отраслевой: мебель индивидуального изготовления. */
export const POSITION_PREFIX = 'МИ';

/** «МИ-поз.3» — то, что пишут в заголовке вида и в спецификации. */
export function positionCode(index: number): string {
  return `${POSITION_PREFIX}-поз.${Math.max(1, Math.round(index))}`;
}

export type ProjectPosition = {
  /** Номер по объекту, начиная с единицы. */
  index: number;
  code: string;
  zone: ZoneKind;
  /** «Кухня», «Спальня» — как называется изделие в штампе. */
  title: string;
};

/**
 * Позиции объекта по его зонам.
 *
 * Порядок задаётся списком зон и не пересчитывается: номер позиции попадает
 * в подписанные документы, и перенумеровать его задним числом — значит
 * поссорить чертёж со сметой, которую клиент уже видел.
 */
export function projectPositions(zones: ZoneKind[]): ProjectPosition[] {
  return zones.map((zone, i) => ({
    index: i + 1,
    code: positionCode(i + 1),
    zone,
    title: PRODUCT_TITLE[zone],
  }));
}

/* ─────────────────────────  Номера модулей на видах  ───────────────────────── */

/**
 * НОМЕР МОДУЛЯ — то, по чему цех сверяет деталь с чертежом.
 *
 * `МИ-поз.N` нумерует ИЗДЕЛИЕ на объекте, а внутри изделия свои номера у
 * модулей: их пишут в кружке прямо на виде, и по ним читают детализировку.
 * Без номера на виде список деталей приходится сопоставлять по подписи
 * («Карго», «Дверца») — а таких подписей на ряде несколько одинаковых.
 *
 * Порядок фиксирован: нижний ряд слева направо, затем верхний слева
 * направо. Номер попадает в подписанные документы, поэтому он обязан
 * получаться из состава детерминированно, а не из счётчика отрисовки.
 */
export function moduleNumbers(run: Pick<Run, 'modules' | 'upperSegments'>): Map<string, number> {
  const ordered: Module[] = [
    ...[...run.modules].sort((a, b) => a.offsetMm - b.offsetMm),
    ...run.upperSegments
      .flatMap((segment) => segment.modules)
      .sort((a, b) => a.offsetMm - b.offsetMm),
  ];

  return new Map(ordered.map((unit, i) => [unit.id, i + 1]));
}

/** Диаметр кружка позиции на бумаге, миллиметры. Отраслевой размер. */
export const POSITION_CIRCLE_MM = 7;
