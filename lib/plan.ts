/**
 * Тариф организации.
 *
 * Пока значений ровно два, и различает их одно: тратит ли организация
 * настоящие запросы к модели.
 *
 *   trial (по умолчанию)  — рабочая организация, генерация как обычно
 *   demo                  — витрина для мебельной компании: генерация
 *                           выключена НА СЕРВЕРЕ, картинка положена руками
 *
 * `orgs.plan` — свободный текст со значением по умолчанию `trial`, поэтому
 * никакой миграции здесь нет и быть не должно: чужие организации ничего
 * не замечают.
 */

export const DEMO_PLAN = 'demo';

/**
 * Организация на демо-тарифе.
 *
 * ПРОВЕРЯЕТСЯ ЯВНЫМ РАВЕНСТВОМ, а не «не trial»: неизвестный тариф,
 * опечатка в поле или новое значение в будущем не должны молча выключать
 * генерацию у работающей компании. Выключаем только то, что прямо названо.
 */
export function isDemoPlan(plan: string | null | undefined): boolean {
  return String(plan ?? '').trim().toLowerCase() === DEMO_PLAN;
}
