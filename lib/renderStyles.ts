/**
 * СЪЁМКА — общая для всех стилей.
 *
 * Стиль отвечает за материалы и настроение, а «плоско» или «дорого» решает
 * съёмка: объектив, свет и тени. Рендеры выходили плоскими именно потому,
 * что о свете было сказано одной строкой — «естественный свет из окна».
 * Кухню снимают в три источника, и это надо называть.
 */
