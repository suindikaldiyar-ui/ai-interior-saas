export type CountertopKind = 'ldsp' | 'quartz' | 'solid_wood';

export interface RunOptions {
  hasUpper: boolean;
  upperToCeiling: boolean;
  hardwareClass: HardwareClass;
  countertop: CountertopKind;
  /** Антресоль — второй ярус верхнего ряда до потолка. */
  hasCornice: boolean;
  integratedHandles: boolean;
}

/**
 * Зона квартиры. Полностью просчитана кухня; остальные заведены габаритами
 * и составом статей — см. lib/millwork/zones.ts.
 */
export type ZoneKind = 'kitchen' | 'bedroom' | 'living' | 'bathroom' | 'hallway';

export interface Run {
  id: string;
  /** Зона, под которую собран ряд. По умолчанию кухня. */
  zone?: ZoneKind;
  /** Чем закрыт ряд. Двери-купе считаются по м² и меняют глубину корпуса. */
  doorSystem?: DoorSystem;
  /** Длина ряда по стене. */
  lengthMm: number;
  ceilingHeightMm: number;
  modules: Module[];
  upperSegments: UpperSegment[];
  options: RunOptions;
  /**
   * Антресоль над верхним рядом. Пусто — её нет вовсе.
   *
   * Живёт на ряду, а не в требованиях: `applyOps` пересобирает верхний
   * ряд после каждой правки, и антресоль обязана пережить пересборку
   * вместе со своим материалом.
   */
  mezzanine?: MezzanineSpec;
  /**
   * ФРЕЗЕРОВКА, НАЗНАЧЕННАЯ РЯДАМ ОБЪЕКТА.
   *
   * Мебельщик назначает её полосой, а не модулю: «низ Модерн, верх
   * ровный». Здесь лежит ссылка на позицию каталога для каждой полосы;
   * пусто у полосы — читается назначенное НИЖНЕМУ ряду, то есть «как у
   * нижних».
   *
   * Это НАСЛЕДОВАНИЕ, а не копия: поменяли низ — верх, у которого своего
   * нет, поехал за ним. Отвечает на это одна функция `millingFor`
   * ([lib/millwork/milling.ts](lib/millwork/milling.ts)); разложи ответ
   * по вызывающим — и смета, сцена, чертёж и деталировка назовут разную
   * фрезеровку на одном фасаде.
   *
   * Живёт на РЯДУ по той же причине, что антресоль и ригели: читают её
   * функции, которые видят только `unit` и `run`.
   */
  milling?: Partial<Record<'base' | 'upper' | 'tall' | 'drawers' | 'mezzanine', string>>;
  /**
   * МАТЕРИАЛ КОРПУСА, НАЗНАЧЕННЫЙ РЯДАМ ОБЪЕКТА.
   *
   * Устроен ровно как `milling` и читается той же лестницей: модуль →
   * полоса → низ (`carcassFor`). Вторая лестница наследования разошлась
   * бы с первой на первом же ряду, где назначено и то, и другое.
   *
   * `shelves` и `partitions` — не полосы, а ДЕТАЛИ: свой декор полок и
   * перегородок по всему ряду. Читает их та же `carcassFor` — деталь со
   * своим декором сильнее корпуса, без него она как корпус.
   */
  carcass?: Partial<Record<'base' | 'upper' | 'tall' | 'drawers' | 'mezzanine' | 'shelves' | 'partitions', string>>;
  /**
   * СТОЛЕШНИЦА ИЗ КАТАЛОГА МАТЕРИАЛОВ: позиция и её поверхность.
   *
   * Живёт на ряду по той же причине, что `carcass`: выбор обязан пережить
   * пересборку ряда и закрытие объекта, а сохраняется ряд. Пусто —
   * столешница считается по типу из `options.countertop`, как раньше.
   * Здесь лежит ССЫЛКА, а не копия: цена и цвет остаются в каталоге
   * (ловушка 22).
   */
  countertopMaterial?: { itemId: string; surface?: string };
  /**
   * МАТЕРИАЛ ФАСАДОВ КУХНИ — выбор «на всю кухню» по роли «фасад» (слой 52).
   *
   * Лежит на ряду рядом с `carcass` (роль «корпус») и `countertopMaterial`
   * (роль «столешница»). Модуль, у которого своего фасада нет, — добор
   * после сужения, модуль из библиотеки, шкаф автосборки — берёт его в
   * конце каждой правки (`applyOps`). Свой фасад модуля сильнее: выбор на
   * модуле человек делал отдельно, и материал кухни его не трогает.
   */
  kitchenFront?: FrontSpec;
  /**
   * СИСТЕМА КУПЕ РЯДА (HARDWARE-01): ссылка на позицию каталога
   * (`category: 'sliding'`). Полотна купе закрывают ряд целиком, поэтому
   * система одна на ряд. Пусто — как раньше: «Система купе» в смете по
   * ставке, без артикула.
   */
  slidingSystemItemId?: string;
  /**
   * РИГЕЛИ НАД ЭТИМ РЯДОМ, в координатах ряда.
   *
   * Живут на ряду по той же причине, что и антресоль: высоту модуля
   * считает одна функция (`moduleCarcassHeightMm`), и она получает
   * только `unit` и `run`. Чертёж и сцена тоже видят ряд, а не замер —
   * без этого поля ригель пришлось бы прокидывать четырьмя разными
   * путями, и они разошлись бы на первой правке.
   *
   * Пусто — потолок над рядом ровный. Ряды, собранные до этого слоя,
   * поля не имеют, и отпечаток у них не меняется.
   */
  beams?: Opening[];
  /**
   * КОЛОННЫ, КОРОБА И ВЫСТУПЫ СТЕНЫ У ЭТОГО РЯДА, в координатах ряда (слой 56).
   *
   * Живут на ряду по той же причине, что и ригели: столешницу, цоколь и
   * фартук считают функции, видящие только ряд, и обойти препятствие они
   * могут, только если оно лежит здесь. Кладёт их замер на каждом показе
   * (`runWithObstacles`), а не сохранение: внесли выступ в замер — ряд
   * узнал о нём сразу. Пусто — у стены ничего не стоит.
   */
  obstacles?: Opening[];
  /**
   * ЧТО У ЭТОГО РЯДА В УГЛУ.
   *
   * Пусто у прямой кухни — и ряды, собранные до этого слоя, не меняются.
   */
  corner?: RunCorner;
  /**
   * СТОЛЕШНИЦА НАД ПУСТОТОЙ У СТЕНЫ СНЯТА ЧЕЛОВЕКОМ.
   *
   * У ряда угловой кухни столешница доходит до стены по умолчанию: хвост
   * меньше 150 мм закрывается добором, больше — плитой над пустотой.
   * Человек вправе плиту над пустотой снять — тогда здесь `cut` у того
   * конца ряда. Умолчание не пишется (ловушка 246).
   */
  counterEnds?: { start?: 'cut'; end?: 'cut' };
  /**
   * ШКОЛА ЦЕХА, по которой собран этот ряд: глубины и высоты.
   *
   * Живёт на ряду по той же причине, что и ригели: высоту и глубину
   * модуля считают функции, которым видно только `unit` и `run`. Пусто —
   * умолчания продукта, и ряды, собранные до этого слоя, не едут.
   *
   * Здесь лежат только ПЕРВИЧНЫЕ величины настроек. Рабочая поверхность
   * и низ верхнего ряда сюда не пишутся: они считаются формулой из них
   * же, и копия разошлась бы с оригиналом.
   */
  production?: ProductionSettings;
  /**
   * СТЕНА ЗАМЕРА, вдоль которой стоит ряд.
   *
   * Она же идентичность ряда в идентификаторах его модулей. Номер ряда
   * в композиции для этого не годится: он меняется при смене формы, а
   * стена остаётся той же стеной.
   *
   * Пусто — ряд один, и столкнуться его модулям не с кем: у объектов,
   * сохранённых до этого слоя, идентификаторы не меняются.
   */
  wallId?: string;
  /** Сумма ширин и зазоров минус длина ряда. Обязана быть нулевой. */
  residualMm: number;
  warnings: string[];
  /** Отпечаток состава: по нему сверяются чертёж, смета и рендер. */
  fingerprint: string;
}

