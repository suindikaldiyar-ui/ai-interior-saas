export type MillworkOp =
  /**
   * Добавить модуль. `variant` задаёт НАЧИНКУ сразу: «+» в свободной
   * сборке ставит готовый модуль (карго 400, витрину 600), а не пустое
   * место, которому потом выбирают назначение вторым жестом.
   */
  | {
      op: 'add_module';
      kind: ModuleKind;
      widthMm?: number;
      afterModuleId?: string;
      appliance?: ApplianceKind;
      variant?: ModuleVariantKind;
      /**
       * ЛЕВЫЙ КРАЙ НОВОГО МОДУЛЯ, мм от угла.
       *
       * Висящий ряд разорван окном, колонной и выступом, и пустота
       * бывает ВПЛОТНУЮ К ПРЕГРАДЕ: за окном, над которым шкафа нет.
       * «За соседом» туда не поставить — сосед стоит по другую сторону
       * окна, и модуль въехал бы в окно. В висящем ряду `afterModuleId`
       * тогда называет РЯД, а отметка — место.
       *
       * Пусто — как раньше: вплотную за соседом, а в нижнем ряду
       * свободной сборки — в первое подходящее место слева.
       */
      atMm?: number;
      /**
       * В КАКОЙ ВИСЯЩИЙ РЯД. Пустой верхний ряд и пустая антресоль —
       * законные места (свободная сборка), и назвать их через соседа
       * нечем: соседей там нет. Пусто — как раньше: ряд задаёт сосед.
       */
      row?: 'upper' | 'mezzanine';
    }
  | { op: 'remove_module'; moduleId: string }
  /**
   * СТОЛЕШНИЦА НАД ПУСТОТОЙ У СТЕНЫ: снять (`cut: true`) или вернуть.
   * Работает только у ряда угловой кухни и только у конца, где хвост не
   * меньше 150 мм: меньший хвост закрывается добором, его не снимают.
   */
  | { op: 'set_counter_end'; end: 'start' | 'end'; cut: boolean }
  /**
   * ЗАМЕНА МЕСТА — ОДНА ОПЕРАЦИЯ.
   *
   * Библиотека модулей меняет на месте ТРИ вещи сразу: чем модуль стал
   * (`variant`), какого он вида (`kind`) и какой ширины (`widthMm`).
   * Тремя операциями подряд это было бы три пересчёта ряда и три
   * промежуточных состояния, каждое из которых может не собраться:
   * узкий вариант в широком месте, широкий в узком.
   *
   * Материал фасада, корпуса и ручка при этом ПЕРЕЕЗЖАЮТ: человек
   * выбирал их для этого места, а не для этого типа модуля.
   */
  | {
      op: 'replace_module';
      moduleId: string;
      kind: ModuleKind;
      appliance?: ApplianceKind;
      /** Чем модуль стал: ключ из `MODULE_VARIANTS`. */
      variant?: ModuleVariantKind;
      /** Новая ширина. Пусто — остаётся прежняя. */
      widthMm?: number;
      /** Человек подтвердил, что отсеки модуля снимаются (см. `set_variant`). */
      dropBays?: boolean;
    }
  | { op: 'set_width'; moduleId: string; widthMm: number }
  | { op: 'set_fronts'; moduleId: string; drawerCount: number; dropBays?: boolean }
  /** Сменить начинку модуля в зонах без техники: штанга вместо полок. */
  | { op: 'set_section'; moduleId: string; section: SectionKind; dropBays?: boolean }
  /**
   * Сменить вариант места: карго вместо дверцы, сушилка над мойкой.
   *
   * `dropBays` (и у замены, секции и числа фронтов) — ПОДТВЕРЖДЕНИЕ
   * ЧЕЛОВЕКА (R02A.1): эти операции ставят наполнение варианта заново, и
   * отсеки модуля — перегородки, полки отсеков, блоки ящиков — уходят. Без
   * подтверждения движок отказывает словами и ряд не меняет. Ставит его
   * только экран после «Снять отсеки и заменить» (`confirmBayLoss`);
   * модель и командная строка его не ставят.
   */
  | { op: 'set_variant'; moduleId: string; variant: ModuleVariantKind; dropBays?: boolean }
  /**
   * Материал фасада. `moduleId: 'all'` — весь ряд: так применяется
   * готовый дизайн, и так же он потом правится поштучно.
   */
  | { op: 'set_front'; moduleId: string; front: FrontSpec }
  /**
   * Фасад ОДНОЙ створки или ящика (P3D-MDF): `leaf` — `door:0`, `drawer:1`.
   * `front: null` — створка снова с фасадом модуля.
   */
  | { op: 'set_leaf_front'; moduleId: string; leaf: string; front: FrontSpec | null }
  /**
   * Габарит КОНКРЕТНОГО прибора: ниша пересчитывается, зазоры остаются
   * отраслевыми. `appliance` обязателен — в колонне приборов два, и
   * «размер модуля» там ничего не значит.
   */
  | {
      op: 'set_appliance_size';
      moduleId: string;
      appliance: ApplianceKind;
      size: ApplianceSize;
    }
  /**
   * Перенос модуля. `afterModuleId` — перестановка в порядке (так правит
   * модель); `offsetMm` — перенос на место вдоль ряда, шагом 50 мм: так
   * двигает модуль рука в свободной сборке. Соседи не раздвигаются.
   */
  | { op: 'move_module'; moduleId: string; afterModuleId?: string; offsetMm?: number }
  /**
   * Антресоль как отдельная позиция состава: добавить со своей высотой
   * либо снять. Материал ей выбирают тем же `set_front`, что и всем.
   */
  | { op: 'set_mezzanine'; heightMm: number | null }
  /**
   * ОТДЕЛЬНЫЙ ВЕРХНИЙ КОРПУС НАД ШКАФОМ (P2): поставить над выбранным
   * напольным шкафом (`moduleId` — шкаф) и править (`moduleId` — сам
   * корпус). Ширина, глубина, высота — его; `baseHeightMm` — новая высота
   * шкафа под ним, если места до потолка нет (называется ДО нажатия).
   * Снимается обычным `remove_module` по его идентификатору: наполнение
   * шкафа под ним при этом не трогается.
   */
  | {
      op: 'add_overhead' | 'set_overhead';
      moduleId: string;
      heightMm?: number;
      depthMm?: number;
      widthMm?: number;
      baseHeightMm?: number;
    }
  /**
   * Высота высокого шкафа, заданная человеком (P2); `null` — снова по
   * зоне. Опустить можно, только если наполнение влезает.
   */
  | { op: 'set_height'; moduleId: string; heightMm: number | null }
  /**
   * ФРЕЗЕРОВКА: ряду или одному модулю.
   *
   * `scope` — полоса («низ», «верх», «пеналы», «ящики», «антресоль»);
   * `moduleId` — один фасад. Ровно один из двух: назначить «всем ящикам»
   * и «вот этому ящику» одной операцией нельзя, иначе непонятно, что
   * сильнее.
   *
   * `millingId: null` снимает фрезеровку: ровный фасад — это выбор, а не
   * отсутствие выбора.
   */
  | {
      op: 'set_milling';
      millingId: string | null;
      scope?: 'base' | 'upper' | 'tall' | 'drawers' | 'mezzanine';
      moduleId?: string;
    }
  /**
   * Направление открывания фасада. Ложится в `fill.hinge` — туда же, куда
   * его кладёт умолчание, — и потому одинаково видно чертежу, сцене,
   * раскрою и смете.
   */
  | { op: 'set_opening'; moduleId: string; opening: FrontOpening }
  /** Чем открывают фасад: скоба, профиль или нажатие. */
  | { op: 'set_handle'; moduleId: string; handle: HandleKind }
  /**
   * Высота и поворот ручки. Стороны здесь нет намеренно: она напротив
   * петель, и менять её значит менять направление открывания.
   */
  | {
      op: 'set_handle_spot';
      moduleId: string;
      level?: HandleLevel;
      turn?: HandleTurn;
      /** Сторона, если её всё же попросили: ответим словами. */
      place?: string;
    }
  /**
   * Материал корпуса: полосе, одному модулю или ДЕТАЛЯМ ряда (полкам,
   * перегородкам), как фрезеровка. `itemId: null` — «как у цеха», то есть
   * отказ от декора. Адрес у правки один.
   */
  | {
      op: 'set_carcass';
      moduleId?: string;
      scope?: 'base' | 'upper' | 'tall' | 'drawers' | 'mezzanine';
      part?: 'shelves' | 'partitions';
      itemId: string | null;
    }
  /**
   * СТОЛЕШНИЦА ИЗ КАТАЛОГА МАТЕРИАЛОВ — на ряд целиком.
   *
   * `itemId: null` снимает выбор: столешница снова считается по типу
   * из `options.countertop`.
   */
  | { op: 'set_countertop'; itemId: string | null; surface?: string }
  /**
   * МАТЕРИАЛ ФАСАДОВ КУХНИ — для модулей, которые появятся после выбора.
   * `null` снимает: новые модули снова получают фасад по умолчанию.
   */
  | { op: 'set_kitchen_front'; front: FrontSpec | null }
  /**
   * ФУРНИТУРА ПРОИЗВОДИТЕЛЯ НА МЕСТО МОДУЛЯ (HARDWARE-01). `itemId: null`
   * снимает. Ставится только подходящее: совместимость проверяет
   * `fittingVerdict` по данным позиции и модуля ДО записи, отказ — словами
   * с миллиметрами, и ряд прежний.
   */
  | { op: 'set_fitting'; moduleId: string; slot: FittingSlot; itemId: string | null; bayId?: string }
  /** Система купе ряда — позиция каталога (`category: 'sliding'`); `null` снимает. */
  | { op: 'set_sliding_system'; itemId: string | null }
  /**
   * НАПОЛНЕНИЕ МОДУЛЯ ЦЕЛИКОМ — ОДНА ОПЕРАЦИЯ, А НЕ ПЯТЬ.
   *
   * Жест на чертеже правит `fill`: полку тянут вверх-вниз, границу между
   * ящиками — с сохранением суммы, перегородку — вдоль, треугольник
   * открывания — нажатием. Это ОДНО поле модуля, и заводить под каждую
   * его часть свою операцию значит открыть в одну структуру пять дверей:
   * `set_shelves`, `set_drawer_heights`, `set_divider`, `set_rods` — и
   * шестую на первую же новую величину. Их в `fill` прибавлялось трижды
   * за последние заходы (`handleLevel`, `handleTurn`, `openingChosen`).
   *
   * Две двери туда уже ведут — `set_opening` и `set_handle_spot`, — и обе
   * правят ОДНО названное свойство, а не наполнение. Правка чертежа
   * говорит другое: «вот наполнение этого модуля целиком».
   *
   * Что принять, а что отклонить, решает не форма операции, а проверка
   * после неё: `fillRefusal` называет число, а инварианты ряда стоят там
   * же, где у всех остальных операций.
   */
  | { op: 'set_fill'; moduleId: string; fill: ModuleFill }
  | { op: 'set_option'; key: 'upperToCeiling' | 'hardwareClass' | 'countertop' | 'hasUpper' | 'hasCornice' | 'integratedHandles'; value: string | boolean };

export interface MillworkRequest {
  message: string;
  run: Run;
  requirements: RunRequirements;
}

export interface MillworkResponse {
  reply: string;
  ops: MillworkOp[];
}

/* ─────────────────────────  Проверки  ───────────────────────── */

export type IssueLevel = 'error' | 'warning';

/**
 * Что именно не так. Две категории по смыслу разные и показываются
 * в разных местах: поломка раскладки — это баг конфигуратора, а расхождение
 * с коммуникацией — нормальная рабочая ситуация, которую решают на объекте.
 * Смешивать их в один список нельзя: тогда обе выглядят как одна поломка.
 */
export type IssueKind = 'layout' | 'comm' | 'fit';

export interface LayoutIssue {
  kind: IssueKind;
  level: IssueLevel;
  moduleId?: string;
  /** Позиция вдоль ряда, куда указывает флажок на плане. */
  atMm?: number;
  message: string;
}
