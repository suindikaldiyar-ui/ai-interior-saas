export type OpeningKind =
  | 'window'
  | 'door'
  | 'arch'
  | 'niche'
  | 'column'
  | 'pipe_box'
  /**
   * РИГЕЛЬ: выступ на потолке, под который ряд не встаёт в полную высоту.
   *
   * Балка или короб по потолку — это такой же объект стены, как окно,
   * только сверху: у него есть место от угла, ширина и то, насколько он
   * опускается. Поэтому он и живёт в `Opening`, а не в своём списке:
   * замер, сохранение объекта, композиция и чертёж уже возят проёмы, и
   * второй путь для той же величины разошёлся бы с первым.
   */
  | 'beam'
  /**
   * ВЫСТУП СТЕНЫ: часть стены, вышедшая в комнату, — пилон, утолщение у
   * стояка, кирпичный выступ. Меряется как колонна: от угла, ширина,
   * вынос от стены (`depthMm`); стоит на полу, а высота по умолчанию —
   * до потолка, допущением (`resolveSurvey`). Мебель его обходит: «стена
   * выступает — рядом с ней ставим дальше».
   */
  | 'protrusion';

export interface Opening {
  id: string;
  kind: OpeningKind;
  /** Расстояние от левого угла стены до левого края проёма. */
  fromCornerMm: number;
  widthMm: number;
  /**
   * Низ проёма от пола. Для двери 0.
   *
   * У РИГЕЛЯ не читается вовсе: он висит на потолке, и его низ считается
   * из высоты потолка (`beamBottomMm`). Держать здесь копию этой отметки
   * значит завести вторую величину, которая устареет от первой же правки
   * высоты потолка.
   */
  sillMm: number;
  /**
   * Высота проёма. У РИГЕЛЯ — насколько он опускается от потолка.
   *
   * Замерщик меряет именно это: до потолка он рулеткой не достаёт, а
   * свес балки видит. См. `beamDropMm`.
   */
  heightMm: number;
  /** Насколько выступает или углубляется — для ниш, коробов и колонн. */
  depthMm?: number;
}

